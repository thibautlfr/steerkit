#!/usr/bin/env node
// Writes src/tokens.css and src/fonts/ from the art direction of thibaut-lefrancois.com,
// whose source is the private portfolio repository. The site is styled from these files only,
// so it builds without the portfolio (CI, contributors); `--check` fails when they no longer
// match it, and skips when the portfolio is not there.
//
//   node scripts/tokens.mjs          write src/tokens.css and src/fonts/
//   node scripts/tokens.mjs --check  exit 1 if either is stale
//
// The portfolio is found at PORTFOLIO_DIR, or ~/Documents/Github/portfolio. Its own parser
// (src/lib/css-tokens.ts) reads the stylesheets, so nothing here knows a value.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const portfolioDir =
	process.env.PORTFOLIO_DIR ?? join(homedir(), "Documents/Github/portfolio");
const check = process.argv.includes("--check");
const docs = join(import.meta.dirname, "..");
const outCss = join(docs, "src/tokens.css");
const outFonts = join(docs, "src/fonts");

if (!existsSync(join(portfolioDir, "src/styles/tokens"))) {
	if (check) {
		console.log(`tokens: no portfolio at ${portfolioDir}, check skipped`);
		process.exit(0);
	}
	throw new Error(`No portfolio at ${portfolioDir} (set PORTFOLIO_DIR)`);
}

const from = (path) => pathToFileURL(join(portfolioDir, path)).href;
const { parseTokens, toScope, resolveHex } = await import(
	from("src/lib/css-tokens.ts")
);
const { SHADER_PALETTE } = await import(
	from("src/scripts/hero-shader/palette.ts")
);

const read = (path) => readFileSync(join(portfolioDir, path), "utf8");
// The Radix scales are the ones color.css imports
const scales = [
	...read("src/styles/tokens/color.css").matchAll(
		/@import "(@radix-ui\/colors\/[\w-]+\.css)"/g,
	),
].map(([, path]) => `node_modules/${path}`);
const sheets = [
	...scales,
	...["color", "typography", "space", "layout", "motion"].map(
		(name) => `src/styles/tokens/${name}.css`,
	),
];
for (const sheet of sheets) {
	if (!existsSync(join(portfolioDir, sheet)))
		throw new Error(
			`Missing ${sheet} in ${portfolioDir} (pnpm install there?)`,
		);
}
const tokens = sheets.flatMap((sheet) => parseTokens(read(sheet)));
const scope = toScope(tokens);

// The tokens a documentation page has a use for; the portfolio's own (the hero, the
// breadcrumb trail, the email, the artworks) stay there
const kept = [
	/^--space-\d+$/,
	/^--layout-(gutter|measure|measure-wide)$/,
	/^--border-/,
	/^--tap-size$/,
	/^--focus-/,
	/^--font-code$/,
	/^--font-size-(step-|data$)/,
	/^--font-weight-(?!wordmark)/,
	/^--line-height-/,
	/^--letter-spacing-title$/,
	/^--duration-/,
	/^--ease-/,
];

// The faces, served from src/fonts/: the portfolio's subsets (scripts/fonts.sh there)
const faces = [
	{ family: "Stack Sans Headline", file: "stack-sans-headline", weight: "700" },
	{ family: "Stack Sans Text", file: "stack-sans-text", weight: "300 600" },
	{ family: "Fragment Mono", file: "fragment-mono", weight: "400" },
];

const lines = [
	"/* Generated by scripts/tokens.mjs from the art direction of thibaut-lefrancois.com.",
	"   Do not edit: run `pnpm -F docs tokens` after a change there. */",
	"",
];
for (const { family, file, weight } of faces) {
	lines.push(
		"@font-face {",
		`\tfont-family: "${family}";`,
		"\tfont-style: normal;",
		`\tfont-weight: ${weight};`,
		"\tfont-display: swap;",
		`\tsrc: url("./fonts/${file}.woff2") format("woff2");`,
		"}",
		"",
	);
}
lines.push(":root {", "\tcolor-scheme: light;", "", "\t/* Colour roles */");
for (const { name, value } of tokens) {
	if (!name.startsWith("--color-")) continue;
	const hex = resolveHex(value, scope);
	if (hex) lines.push(`\t${name}: ${hex};`);
}
lines.push(
	"",
	"\t/* The shader's palette: the ink cell and what is drawn on it */",
);
for (const [name, hex] of Object.entries(SHADER_PALETTE))
	lines.push(`\t--shader-${name}: ${hex};`);
lines.push(
	"",
	"\t/* Faces */",
	'\t--font-title: "Stack Sans Headline", system-ui, sans-serif;',
	'\t--font-text: "Stack Sans Text", system-ui, sans-serif;',
	'\t--font-data: "Fragment Mono", ui-monospace, monospace;',
	"",
	"\t/* Type, space, layout and motion */",
);
for (const { name, value } of tokens) {
	if (kept.some((pattern) => pattern.test(name)))
		lines.push(`\t${name}: ${value};`);
}
lines.push("}", "");
// Motion is set to zero under reduced motion, as in the portfolio's motion.css
const durations = tokens.filter(({ name }) => name.startsWith("--duration-"));
lines.push(
	"@media (prefers-reduced-motion: reduce) {",
	"\t:root {",
	...durations.map(({ name }) => `\t\t${name}: 0ms;`),
	"\t}",
	"}",
	"",
);
const css = lines.join("\n");

const fonts = faces.map(({ file }) => ({
	file: `${file}.woff2`,
	data: readFileSync(join(portfolioDir, `src/assets/fonts/${file}.woff2`)),
}));

if (check) {
	const stale = [];
	if (!existsSync(outCss) || readFileSync(outCss, "utf8") !== css)
		stale.push("src/tokens.css");
	for (const { file, data } of fonts) {
		const path = join(outFonts, file);
		if (!existsSync(path) || !readFileSync(path).equals(data))
			stale.push(`src/fonts/${file}`);
	}
	if (stale.length) {
		console.error(
			`tokens: ${stale.join(", ")} no longer match the portfolio: run pnpm -F docs tokens`,
		);
		process.exit(1);
	}
	console.log("tokens: in step with the portfolio");
} else {
	writeFileSync(outCss, css);
	mkdirSync(outFonts, { recursive: true });
	for (const { file, data } of fonts) writeFileSync(join(outFonts, file), data);
	console.log(`tokens: wrote src/tokens.css and ${fonts.length} fonts`);
}
